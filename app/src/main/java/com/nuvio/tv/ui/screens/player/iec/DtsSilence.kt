    private val multichannel: ByteArray by lazy { decode(MULTICHANNEL_HEX) }
    private val stereo: ByteArray by lazy { decode(STEREO_HEX) }

    fun coreFrame(multichannelLayout: Boolean): ByteArray =
        (if (multichannelLayout) multichannel else stereo).copyOf()

    fun coreIsMultichannel(head: ByteArray): Boolean? {
        if (head.size < 9) return null
        val bigEndian = when {
            head[0] == 0x7F.toByte() && head[1] == 0xFE.toByte() && head[2] == 0x80.toByte() && head[3] == 0x01.toByte() -> true
            head[0] == 0xFE.toByte() && head[1] == 0x7F.toByte() && head[2] == 0x01.toByte() && head[3] == 0x80.toByte() -> false
            else -> return null
        }
        fun byteAt(i: Int): Int = (if (bigEndian) head[i] else head[i xor 1]).toInt() and 0xFF
        val amode = ((byteAt(7) and 0x0F) shl 2) or (byteAt(8) ushr 6)
        return amode > STEREO_AMODE_MAX
    }

    fun coreSampleCount(head: ByteArray): Int {
        if (coreIsMultichannel(head) == null) return 0
        val bigEndian = head[0] == 0x7F.toByte()
        fun byteAt(i: Int): Int = (if (bigEndian) head[i] else head[i xor 1]).toInt() and 0xFF
        val nblks = ((byteAt(4) and 0x01) shl 6) or (byteAt(5) ushr 2)
        return (nblks + 1) * 32
    }

    private fun decode(hex: String): ByteArray = ByteArray(hex.length / 2) { i ->
        ((Character.digit(hex[2 * i], 16) shl 4) or Character.digit(hex[2 * i + 1], 16)).toByte()
    }

